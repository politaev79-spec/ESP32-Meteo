#ifndef CONFIG_H
#define CONFIG_H

// ===========================================================================
//  ESP32-C3 Super Mini + BMP280 — метеостанция
// ===========================================================================

// ---------------------------------------------------------------------------
//  BMP280 (I2C)
//  Пины перенесены с GPIO8/9 на GPIO0/1 (GPIO8=LED, GPIO9=strapping).
//  Если у тебя другие пины — поменяй здесь.
// ---------------------------------------------------------------------------
#define BMP_SDA_PIN     0
#define BMP_SCL_PIN     1
#define BMP_I2C_FREQ    100000
#define BMP_ADDR        0x76        // 0x76 или 0x77 (у некоторых модулей адрес переключается)

// Комбинированный модуль AHT20 (температура/влажность) + BMP280 (давление)
#define AHT20_ADDR      0x38

// Частота опроса датчика (мс) и отправки данных в Web UI.
#define SENSOR_INTERVAL_MS   2000

// ---------------------------------------------------------------------------
//  WiFi: режим AP (открытая сеть) — доступ с телефона напрямую, без роутера.
//  Если задать STA_SSID (не пусто) — устройство подключится к домашней сети,
//  а AP продолжит работать параллельно.
// ---------------------------------------------------------------------------
#define AP_SSID            "ESP32-Meteo"
#define AP_IP              192, 168, 4, 1
#define AP_GATEWAY         192, 168, 4, 1
#define AP_SUBNET          255, 255, 255, 0
#define AP_CHANNEL         1
#define AP_MAX_CONNECT     4

static const char* STA_SSID     = "";   // например "MyHomeWiFi" (пусто = только AP)
static const char* STA_PASSWORD = "";

#define WEB_PORT          80

#endif // CONFIG_H
