#ifndef CONFIG_H
#define CONFIG_H

// ===========================================================================
//  ESP32-C3 Super Mini + BMP280 — метеостанция
// ===========================================================================

// ---------------------------------------------------------------------------
//  BMP280 (I2C)
//  ЧИСТЫЕ пины GPIO0/1 (НЕ LED, НЕ BOOT).
//  Была попытка GPIO8/9 (LED + BOOT) — связь нестабильна (то находит, то нет),
//  показания «мусорные». Поэтому заново GPIO0/1. ПОТРЕБУЕТСЯ ПЕРЕТКНУТЬ ПРОВОДА:
//  SDA->GPIO0, SCL->GPIO1, VCC->3V3, GND->GND.
// ---------------------------------------------------------------------------
#define BMP_SDA_PIN     0
#define BMP_SCL_PIN     1
#define BMP_I2C_FREQ    100000
#define BMP_ADDR        0x76        // 0x76 или 0x77 (у некоторых модулей адрес переключается)

// Комбинированный модуль AHT20 (температура/влажность) + BMP280 (давление)
#define AHT20_ADDR      0x38

// ---------------------------------------------------------------------------
//  DS18B20 (KY-001) — уличная температура, протокол 1-Wire на отдельном GPIO.
//  Питание 3V3, подтяжка 4.7к на плате уже есть.
// ---------------------------------------------------------------------------
#define DS18B20_PIN     4

// Частота опроса датчика (мс) и отправки данных в Web UI.
// 15 минут = 15 * 60 * 1000 = 900000 мс.
#define SENSOR_INTERVAL_MS   900000

// ---------------------------------------------------------------------------
//  WiFi: режим AP (открытая сеть) — доступ с телефона напрямую, без роутера.
//  Если задать STA_SSID (не пусто) — устройство подключится к домашней сети,
//  а AP продолжит работать параллельно.
// ---------------------------------------------------------------------------
#define AP_SSID            "ESP32-Meteo"
#define AP_IP              192, 168, 5, 1
#define AP_GATEWAY         192, 168, 5, 1
#define AP_SUBNET          255, 255, 255, 0
#define AP_CHANNEL         1
#define AP_MAX_CONNECT     4

static const char* STA_SSID     = "";   // например "MyHomeWiFi" (пусто = только AP)
static const char* STA_PASSWORD = "";

// Режим сети: 0 = только AP (без интернета), 2 = AP + домашний Wi-Fi (интернет).
// AP всегда работает как «бонус»; домашний Wi-Fi — первичный источник интернета.
#define NET_MODE        2

// Максимум сохранённых Wi-Fi сетей
#define MAX_NET         5

#define WEB_PORT          80

// Часовой пояс для времени (NTP), в секундах. 10800 = UTC+3 (Москва).
#define TZ_OFFSET_SECONDS  10800

// ---------------------------------------------------------------------------
//  МЕСТОПОЛОЖЕНИЕ (для коррекции высоты и отображения на карте)
//  Широта/долгота и известная высота места (м) — введите свои значения.
//  REF_ALTITUDE > 0 => калибруется опорное давление, чтобы высота
//  показывала реальную высоту места (меньше «гуляет» от погоды).
// ---------------------------------------------------------------------------
#define LATITUDE       55.7558   // например Москва
#define LONGITUDE      37.6173
#define REF_ALTITUDE   150.0     // реальная высота места, м (0 = без коррекции)

// ---------------------------------------------------------------------------
//  КОРРЕКЦИЯ ТЕМПЕРАТУРЫ (калибровка ± °C): прибавляется к показаниям.
//  Установить, если датчик врёт (например, DS18B20_CAL_OFFSET = -1.5).
// ---------------------------------------------------------------------------
#define DS18B20_CAL_OFFSET  0.0   // поправка уличного DS18B20
#define BMP_TEMP_CAL_OFFSET 0.0   // поправка домашнего BMP280

#endif // CONFIG_H
